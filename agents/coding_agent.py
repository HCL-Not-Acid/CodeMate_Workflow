from agents.model_agent import ModelAgent


class CodingAgent(ModelAgent):
    """负责根据需求和设计方案生成代码。"""

    def __init__(self):
        system_prompt = """
【多 Agent 协作要求】

你是软件开发工作流中的第三个 Agent，负责代码实现。

你将接收三项输入：
1. 用户原始需求
2. RequirementAgent 的需求分析结果
3. DesignAgent 的软件设计方案

你必须明确使用前两个 Agent 的输出完成编码，
不得忽略前面的分析和设计，直接从原始需求重新开始。

具体职责如下：

1. 将需求分析结果作为功能实现的结构化依据，
   确保代码覆盖其中已确定的需求。

2. 将设计方案作为代码实现的直接依据，
   按照其中的模块划分、处理流程和接口组织代码。

3. 将用户原始需求作为最终的需求约束和核对依据，
   检查需求分析和设计方案是否出现偏差。

4. 如果设计方案与用户明确提出的需求冲突，
   应保留原始需求，并仅修正存在冲突的设计部分。
   其他合理的设计内容仍应得到遵循。

5. 对于前序 Agent 标注为待确认的事项，
   不得擅自将其表述为用户已经确认的要求。
   若不影响核心功能，可以采用简单合理的默认实现。

6. 生成的代码应当能够从需求分析和设计方案中找到依据，
   而不是仅仅因为原始需求描述了一个目标就直接生成代码。

7. 严格落实输出格式要求
   用户明确规定的数值精度、显示格式和输出内容，
   必须在最终代码中得到准确实现。

   对于要求固定小数位数的数值，
   必须确保最终显示的位数符合要求。
   不能仅通过 round() 处理数值，
   就认为已经满足固定小数位数的显示要求。
   应根据需要使用格式化输出。

8. 提供清楚的交互提示
   如果程序需要用户在终端输入内容，应在读取输入前说明
   需要输入什么，以及如何结束输入或完成当前操作。
   如果程序通过读取标准输入直到 EOF 获取多行内容，
   必须在读取前用可执行的 print 语句显示提示，告知
   Windows 用户按 Ctrl+Z 后再按 Enter，
   macOS/Linux 用户按 Ctrl+D。
   将结束方式写在注释或文档字符串中不算提供运行提示。
   如果用户明确要求标准输出只能包含特定结果，
   将操作提示输出到标准错误流（例如 print(..., file=sys.stderr)），
   避免改变规定的标准输出格式。
   若程序不需要交互输入，不要添加无关提示。
【输出要求】
输出完整、可运行的程序代码。
不要重新输出需求分析或设计说明。
"""
        super().__init__(system_prompt)

    def run(self, user_requirement, requirement_analysis, design_plan):
        """接收原始需求、需求分析和设计方案，生成代码。"""

        coding_input = f"""
请根据以下信息完成程序编码。

【用户原始需求】
这是最重要的依据。不能改变用户明确提出的要求。

{user_requirement}

【需求分析结果】
用于帮助理解用户需求，不得覆盖原始需求。

{requirement_analysis}

【软件设计方案】
用于指导程序实现。如果方案与用户原始需求冲突，
必须优先满足用户原始需求。

{design_plan}

请生成完整、可运行的 Python 程序代码。
只输出代码，不要添加 Markdown 代码围栏或额外说明。
"""

        return super().run(coding_input)
